export const getAllWords = (): string[] => {
  const set = new Set<string>();
  CATEGORIES.forEach(cat => {
    cat.words.forEach(w => {
      const trimmed = w.trim();
      if (trimmed && !trimmed.includes(" ") && !trimmed.includes("-")) {
        set.add(trimmed);
      }
    });
  });
  return Array.from(set);
};

